DROP TABLE IF EXISTS rankings CASCADE;
DROP TABLE IF EXISTS resultados CASCADE;

-- Status aceitos na prova:
-- 'Finalizou' : Atleta completou todo o percurso regulamentar.
-- 'DNF'       : Did Not Finish (Não Concluiu) - Largou, mas abandonou o percurso.
-- 'DNS'       : Did Not Start (Não Largou) - Inscrito que não esteve na largada.

CREATE TABLE resultados (
    id SERIAL PRIMARY KEY,
    atleta_id INT NOT NULL,
    atleta_nome VARCHAR(150),
    tempo_prova TIME,
    status VARCHAR(20) CHECK (status IN ('Finalizou', 'DNF', 'DNS'))
);

CREATE TABLE rankings (
    id SERIAL PRIMARY KEY,
    atleta_id INT NOT NULL,
    atleta_nome VARCHAR(150),
    categoria_id INT NOT NULL,
    tempo_prova TIME,
    posicao_categoria INT,
    posicao_geral INT,
    status VARCHAR(20) CHECK (status IN ('Finalizou', 'DNF', 'DNS'))
);

